#!/usr/bin/env python3
"""Write publications.js from NASA ADS. Needs ADS_API_TOKEN in the environment."""
import html
import json
import os
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

QUERY = ('=author:"Lunde, J. G. S." OR =author:"Lunde, Jonas G. S." '
         'OR =author:"Gahr Sturtzel Lunde, Jonas" OR =author:"Lunde, Jonas Gahr Sturtzel" '
         'OR =author:"Sturtzel Lunde, Jonas Gahr"')
FIELDS = "bibcode,title,author,year,bibstem,volume,page,doi,identifier,doctype"
# Leaves out conference abstracts, talks, proposals, errata and the like.
DOCTYPES = {"article", "eprint", "inproceedings", "phdthesis", "mastersthesis"}
THESES = {"phdthesis": "PhD thesis", "mastersthesis": "Master's thesis"}
OUTPUT = Path(__file__).resolve().parent.parent / "publications.js"
HEADER = "// Generated by scripts/update_publications.py from NASA ADS. Do not edit by hand.\n"


def fetch(token):
    params = urllib.parse.urlencode(
        {"q": QUERY, "fl": FIELDS, "rows": 2000, "sort": "date desc, bibcode desc"})
    request = urllib.request.Request(
        "https://api.scixplorer.org/v1/search/query?" + params,
        headers={"Authorization": "Bearer " + token})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)["response"]["docs"]


def clean_title(title):
    title = html.unescape(title)
    title = re.sub(r"<[^>]+>", "", title)
    title = re.sub(r"\\[a-zA-Z]+\{([^}]*)\}", r"\1", title)
    title = title.replace(r"\sim", "~").replace("$", "").replace("\u2500", "\u2013")
    title = title.replace("BEYONDPLANCK", "BeyondPlanck").replace("COSMOGLOBE", "Cosmoglobe")
    title = " ".join(title.split())
    # ADS drops the tilde from "z ~ 3" in some titles.
    return re.sub(r"\bz (\d)", r"z ~ \1", title)


def arxiv_id(doc):
    for identifier in doc.get("identifier", []):
        if identifier.lower().startswith("arxiv:"):
            return identifier[len("arxiv:"):]
    return None


def journal_doi(doc):
    return next((d for d in doc.get("doi", []) if not d.startswith("10.48550")), None)


def reference(doc):
    if doc["doctype"] in THESES:
        return THESES[doc["doctype"]]
    stem = doc.get("bibstem", [""])[0]
    if stem == "arXiv":
        return "arXiv:" + arxiv_id(doc) if arxiv_id(doc) else "arXiv"
    page = doc.get("page", [None])[0]
    place = ", ".join(str(x) for x in (doc.get("volume"), page) if x)
    return f"{stem} {place}".strip()


def link(doc):
    if journal_doi(doc):
        return "https://doi.org/" + journal_doi(doc)
    if arxiv_id(doc):
        return "https://arxiv.org/abs/" + arxiv_id(doc)
    return "https://scixplorer.org/abs/" + doc["bibcode"]


def surname(author):
    name = author.split(",")[0].strip()
    return "Lunde" if "Lunde" in name else name


def authors(doc):
    names = [surname(a) for a in doc["author"]]
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return " & ".join(names)
    return names[0] + " et al."


def entry(doc):
    return {"y": int(doc["year"]), "a": authors(doc), "t": clean_title(doc["title"][0]),
            "v": reference(doc), "u": link(doc)}


def render(docs):
    papers = [entry(d) for d in docs if d.get("doctype") in DOCTYPES and d.get("title")]
    if not papers:
        sys.exit("ADS returned no papers, leaving publications.js as it is")
    rows = ",\n".join("  " + json.dumps(p, ensure_ascii=False) for p in papers)
    return f"{HEADER}const PUBLICATIONS = [\n{rows},\n];\n"


def main():
    token = os.environ.get("ADS_API_TOKEN")
    if not token:
        sys.exit("ADS_API_TOKEN is not set")
    OUTPUT.write_text(render(fetch(token)), encoding="utf-8")


if __name__ == "__main__":
    main()
